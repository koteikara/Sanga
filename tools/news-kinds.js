'use strict';

/**
 * ニュース記事を、**こちらの言葉に分類する**ための語彙。
 *
 * 設計は docs/supporter-timeline-design.md の「イベント・配布・物販の取り込み」を正とする。
 *
 * 公式の記事タイトルと本文は保存も転載もしない（「利用規約から決めたこと」）。
 * 持てるのは事実と、**自分の言葉で書いたラベル**だけ。そこで、題や本文を写すのではなく
 * **手掛かりとして読み、決まった語彙のどれかに振り分ける。**
 *
 * ## この辞書が、やめた辞書と違うところ
 *
 * 本文の意味ラベルを allow-list で読む案は2026-09-11にやめた。外したときに
 * **間違った時刻が出る**ためで、しかも静かに漏れた。
 *
 * こちらは逆で、**外したら何も言わない。** 記事の分類が付かなければ公式のカテゴリを
 * そのまま出し、タイムスケジュールの行の意味が分からなければその行を捨てる。
 * 粗くなるだけで、嘘は出ない。**下限が「分類を入れる前」と同じ**なので、
 * 入れて悪くなることがない。
 */

/**
 * 記事の種類。**上から順に当てて、最初に当たったものを採る。**
 * 「当日券」を先に置くのは、本文に「販売」も出てくるため。並び順に意味がある。
 */
const ARTICLE_KINDS = [
  [/当日券/, '当日券'],
  [/タイムスケジュール|当日のスケジュール/, '当日の流れ'],
  [/増便|交通|シャトル|列車|電車|バス|乗車|運行|駐車|TRAIN|トレイン/, '交通・駐車'],
  [/募集|応募|抽選|プレゼント|申込|申し込み|招待|受付開始/, '応募・抽選'],
  [/お詫び|変更|中止|延期|訂正|不具合/, '変更・お詫び'],
  [/出演|放送|配信|番組|中継/, '放送・配信'],
  [/ホームタウン|デー開催|デー】/, '冠デー'],
  [/グルメ|フード|飲食/, 'スタジアムグルメ'],
  [/先行|一般発売|チケット/, 'チケットの販売'],
  [/発売|販売|受注|商品|取り扱い|取扱/, 'グッズの発売'],
  [/イベント|ブース|広場|体験|ステージ|開催/, '場内の催し'],
];

/** 出しうる種類の全部。検証で閉じていることを確かめる。 */
const KINDS = new Set(ARTICLE_KINDS.map(([, kind]) => kind));

/**
 * 日時を読みに行く種類。**形が揺れないものだけに絞っている。**
 *
 * ここに無い種類の記事からは、日時を1つも取らない。取れなくて困るより、
 * 間違った時刻が出るほうが困る。広げるときは実データで確かめてから。
 */
const EXTRACTABLE_KINDS = new Set(['当日券', 'グッズの発売', '応募・抽選', '交通・駐車', '場内の催し']);

/**
 * 申し込みの締切が出うる種類。
 *
 * **交通・駐車を入れているのは、応援バスの申込期間が同じ形で書かれるため**
 * （2026-09-11 の実測で `申込期間` の下に `9月9日(水)12:00～9月17日(木)15:00まで`）。
 * バスの集合・出発の時刻は採らない。申し込んだ人にしか関係がなく、
 * 特典チケットの引換をフィードに出さないのと同じ理由で、全員の時系列には置かない。
 */
const DEADLINE_KINDS = new Set(['応募・抽選', '交通・駐車']);

/**
 * 種類をイベントIDに使う短い綴り。
 *
 * **IDに種類が要ります。** 「記事＋試合＋時刻」だけだと、同じ時刻の別イベントが
 * ぶつかって片方が消えます。実際、ACLアウェイの記事は開門と当日券がどちらも17:00で、
 * 当日券が黙って落ちていました（2026-09-14に発覚）。
 *
 * ICSのUIDに入るのでASCIIにします。**一度配ったIDは変えません。**
 */
const KIND_SLUGS = {
  '当日の流れ': 'flow',
  '物販ブース': 'booth',
  '当日券': 'sameday',
  '応募の締切': 'entry',
  '場内の催し': 'happening',
  'アウェイ席の前売': 'advance',
};

/** 催しの開催時刻が出うる種類。実測できたのは「場内の催し」だけ。 */
const HAPPENING_KINDS = new Set(['場内の催し']);

/**
 * ACLアウェイのチケット情報が出うる種類。
 *
 * **ふつう「チケットの販売」からは日時を読みません。** 国内のホーム戦は公式の常設ページ
 * （販売スケジュール表）から取っており、記事は同じことを書いているだけだからです。
 *
 * **ACLアウェイだけは違います。** 常設ページにも Jリーグチケットにも載らず、
 * **京都公式の記事が唯一の情報源**です（2026-09-08 の大田戦で確認）。
 *
 *     チケット販売について(アウェイサポーターエリア)
 *       当日発売：キックオフ2時間前（17:00～）
 *       前売販売：試合5日前（9/10）13:00～
 *
 * 相対表記（キックオフ2時間前）と絶対時刻が併記されるので、絶対のほうを採ります。
 */
const ACL_AWAY_TICKET_KINDS = new Set(['チケットの販売', '当日券']);

/**
 * 開門時刻のラベル。**直前の行に単独で置かれる。**
 *
 * ホーム戦の記事は「タイムスケジュール」の表に入場開始を書きますが、ACLアウェイの記事は
 * `開門時間` というラベルで単独に書きます（実測）。表が無くても読めるようにしておきます。
 */
const GATE_LABELS = /^(開門時間|開門|開門時刻|入場開始時間)$/;

/**
 * 催しの開催時刻に付くラベル。**直前の行に単独で置かれる**（`<dt>`/`<dd>` の形）。
 *
 * ラベルが無ければ何も出さない。時刻だけ拾うと、店舗の営業時間や
 * 受け取りの案内まで催しの開始として並んでしまう。
 */
const HAPPENING_LABELS = /^(開催時間|実施時間|開催時刻|実施時刻|時間)$/;

/**
 * 当日のタイムスケジュールに並ぶ説明を、こちらの言葉に直す。
 *
 * **`null` はその行を捨てるという意味。** キックオフと試合終了は matches.json に
 * 持っているので二重に出さない。意味の分からない行も出さない。
 * 時刻だけ出しても「何の時刻か」が分からなければ役に立たない。
 */
const TIMETABLE_ITEMS = [
  [/キックオフ|試合終了|ハーフタイム|終了後/, null],
  [/開門|入場/, '入場開始'],
  [/物販|グッズ|ショップ/, 'グッズ販売開始'],
  [/ブース|場外|広場|出店/, '場外ブース開始'],
  [/ウォームアップ|アップ開始|練習|選手入場/, 'ウォームアップ開始'],
];

/**
 * 当日券をどこで買うか。**同じ記事に2つ並ぶ。**
 *
 * 実測（2026-09-11の柏戦）では、オンラインが試合当日5:00から、スタジアムの窓口が
 * 16:00からだった。**11時間違う。** どちらの話かが分からないと、朝5時に
 * スタジアムへ行きかねない。
 *
 * 売り場の名前は公式の表記をそのまま使わず、ここで2語に畳む。
 */
const TICKET_PLACES = [
  [/売場|売り場|窓口|ボックス|BOX/, '窓口'],
  [/チケットサイト|Ｊリーグチケット|Jリーグチケット|オンライン|ウェブ|WEB/, 'オンライン'],
];

/** 売り場を2語のどちらかに畳む。分からなければ null（添えない）。 */
function placeOfTicket(text) {
  const body = String(text || '');
  for (const [pattern, place] of TICKET_PLACES) {
    if (pattern.test(body)) return place;
  }
  return null;
}

/** タイムスケジュールから出しうるラベルの全部。 */
const TIMETABLE_LABELS = new Set(
  TIMETABLE_ITEMS.map(([, label]) => label).filter(Boolean),
);

/**
 * 題から記事の種類を決める。決められなければ null。
 *
 * 題の頭の `【M/D(曜)◯◯戦】` は対戦相手を示すだけなので、分類からは外す。
 * 相手クラブ名に「バス」などが含まれると誤って交通と判断してしまう。
 */
function kindOfTitle(title) {
  const body = String(title || '').replace(/^【[^】]*】/, '');
  for (const [pattern, kind] of ARTICLE_KINDS) {
    if (pattern.test(body)) return kind;
  }
  return null;
}

/** タイムスケジュールの説明をラベルに直す。捨てるときは null。 */
function labelOfTimetableItem(text) {
  const body = String(text || '');
  for (const [pattern, label] of TIMETABLE_ITEMS) {
    if (pattern.test(body)) return label;
  }
  return null;
}

module.exports = {
  ARTICLE_KINDS,
  KIND_SLUGS,
  ACL_AWAY_TICKET_KINDS,
  GATE_LABELS,
  DEADLINE_KINDS,
  HAPPENING_KINDS,
  HAPPENING_LABELS,
  TICKET_PLACES,
  placeOfTicket,
  KINDS,
  EXTRACTABLE_KINDS,
  TIMETABLE_ITEMS,
  TIMETABLE_LABELS,
  kindOfTitle,
  labelOfTimetableItem,
};
